"""Evidence bundles: every alert traces to rule IDs and event IDs.

An ``EvidenceBundle`` is the auditable artifact for one incident: the
score with its named components, the rules that fired with their
reasons, the full ordered timeline (matched + contextual events), and
the supporting records — the rule-matched events that are the actual
evidence behind the findings (AGENTS.md rule 3).

Untrusted-data handling (AGENTS.md rule 2): every field ingested from
logs is attacker-controllable. Message text in particular is never
mixed into narrative or structured fields; it is carried only in
``EvidenceRecord.untrusted_text``, so downstream consumers (e.g. the
LLM prompt layer) can fence it off strictly as data, never instructions.
Rule ``reasons`` are generated by deterministic rule code, but they
quote entity names, so they too must be treated as untrusted once they
reach a prompt.
"""

from __future__ import annotations

from datetime import datetime
from typing import Sequence

from pydantic import BaseModel, ConfigDict, Field

from .correlate import Incident, member_matches
from .rules.base import RuleMatch
from .scoring import IncidentScore
from .schema import Event, EventType


class RuleFinding(BaseModel):
    """One rule that fired on an incident, with its reasons and evidence.

    Matches of the same rule are merged: all reasons are kept in order
    and the matched event IDs are the union (deduplicated).
    """

    model_config = ConfigDict(strict=True)

    rule_id: str
    severity: int = Field(ge=1, le=10)
    reasons: list[str]
    matched_event_ids: list[str]


class EvidenceRecord(BaseModel):
    """One event as carried in a bundle.

    ``message`` text from the log is quarantined in ``untrusted_text`` —
    it is data, never instructions, and never appears in any other field.
    """

    model_config = ConfigDict(strict=True)

    event_id: str
    timestamp: datetime
    event_type: EventType
    user: str
    host: str
    src_ip: str
    severity: int
    matched: bool
    rule_ids: list[str]
    untrusted_text: str


class EvidenceBundle(BaseModel):
    """Everything needed to audit one incident's alert.

    ``timeline`` holds every event (matched + contextual) in time order;
    ``supporting_records`` is the matched subset — the evidence the
    findings rest on.
    """

    model_config = ConfigDict(strict=True)

    incident_id: str
    score: IncidentScore
    rules: list[RuleFinding]
    timeline: list[EvidenceRecord]
    supporting_records: list[EvidenceRecord]


def build_evidence_bundle(
    incident: Incident,
    score: IncidentScore,
    matches: Sequence[RuleMatch],
    events: Sequence[Event],
) -> EvidenceBundle:
    """Assemble the evidence bundle for one incident.

    ``incident``, ``score``, ``matches`` and ``events`` come from the
    same pipeline run; every event ID carried in the bundle must resolve
    to an ingested event, or the bundle fails to build loudly — no
    finding may reference evidence that does not exist.
    """
    index = {event.event_id: event for event in events}
    unknown = [
        entry.event_id for entry in incident.timeline if entry.event_id not in index
    ]
    if unknown:
        raise ValueError(
            f"incident {incident.incident_id} timeline cites unknown "
            f"event_id(s): {', '.join(sorted(set(unknown)))}"
        )

    rules = _rule_findings(member_matches(incident, matches))
    timeline = [
        _record(index[entry.event_id], entry.matched, entry.rule_ids)
        for entry in incident.timeline
    ]
    supporting_records = [record for record in timeline if record.matched]

    return EvidenceBundle(
        incident_id=incident.incident_id,
        score=score,
        rules=rules,
        timeline=timeline,
        supporting_records=supporting_records,
    )


def _rule_findings(members: Sequence[RuleMatch]) -> list[RuleFinding]:
    """Merge member matches per rule: reasons appended, event IDs unioned."""
    merged: dict[str, RuleFinding] = {}
    for match in sorted(members, key=lambda m: (m.rule_id, m.matched_event_ids)):
        finding = merged.get(match.rule_id)
        if finding is None:
            finding = RuleFinding(
                rule_id=match.rule_id,
                severity=match.severity,
                reasons=[],
                matched_event_ids=[],
            )
            merged[match.rule_id] = finding
        finding.reasons.append(match.reason)
        for event_id in match.matched_event_ids:
            if event_id not in finding.matched_event_ids:
                finding.matched_event_ids.append(event_id)
    return [merged[rule_id] for rule_id in sorted(merged)]


def _record(event: Event, matched: bool, rule_ids: list[str]) -> EvidenceRecord:
    """Project an event into a record, quarantining message text."""
    return EvidenceRecord(
        event_id=event.event_id,
        timestamp=event.timestamp,
        event_type=event.event_type,
        user=event.user,
        host=event.host,
        src_ip=event.src_ip,
        severity=event.severity,
        matched=matched,
        rule_ids=list(rule_ids),
        untrusted_text=event.message,
    )
